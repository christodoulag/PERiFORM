    plot( ...
        axesFit, ...
        xx, ...
        feval(observedFit{1},xx), ...
        'Color',colourPre, ...
        'LineWidth',3, ...
        'HandleVisibility','off');

    plot( ...
        axesFit, ...
        xx, ...
        feval(observedFit{2},xx), ...
        'Color',colourPost, ...
        'LineWidth',3, ...
        'HandleVisibility','off');

    hPreData = plot( ...
        axesFit, ...
        distances, ...
        observedNormRT(1,:), ...
