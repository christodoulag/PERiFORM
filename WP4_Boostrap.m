%% -------------------- LOCAL FUNCTIONS --------------------

function style_wp3_axes(targetAxes)

    % Shared visual style used by the principal WP3 figures
    box(targetAxes,'off');
    pbaspect(targetAxes,[1 1 1]);

    set(targetAxes, ...
        'Color','w', ...
        'FontName','Arial', ...
        'FontSize',13, ...
        'LineWidth',2.2, ...
        'TickDir','out', ...
        'TickLength',[0.025 0.025], ...
        'XColor','k', ...
        'YColor','k', ...
        'Layer','top');
end

function draw_wp3_border_arrow( ...
    targetAxes,xPosition,arrowColour,yTop)

    % Data-coordinate equivalent of the double-headed PPS-border arrows
    % used in WP3. These objects remain aligned when the figure is resized
    % or exported.
    yBottom = 0.012;

    plot( ...
        targetAxes, ...
        [xPosition xPosition], ...
        [yBottom yTop], ...
        '-', ...
        'Color',arrowColour, ...
        'LineWidth',1.4, ...
        'HandleVisibility','off');

    plot( ...
        targetAxes, ...
        xPosition, ...
        yTop, ...
        '^', ...
        'MarkerFaceColor',arrowColour, ...
        'MarkerEdgeColor',arrowColour, ...
        'MarkerSize',7, ...
        'HandleVisibility','off');

    plot( ...
        targetAxes, ...
        xPosition, ...
        yBottom, ...
        'v', ...
        'MarkerFaceColor',arrowColour, ...
        'MarkerEdgeColor',arrowColour, ...
        'MarkerSize',7, ...
        'HandleVisibility','off');
end

function cleanedTrials = remove_wp3_outliers( ...
    trials,cutoff)

    trials = trials(isfinite(trials));

    if isempty(trials)
        cleanedTrials = trials;
        return
    end

    currentMean = mean(trials);
    currentSD = std(trials);

    % WP3 retained all trials when the SD was zero
    if isfinite(currentSD) && currentSD > 0

        zScores = abs( ...
            (trials-currentMean)./currentSD);

        cleanedTrials = ...
            trials(zScores < cutoff);

    else
        cleanedTrials = trials;
    end
end

function [bootMeanRT,bootBorder,bootR2,nAttempts] = ...
    run_wp3_bootstrap( ...
        conditionData, ...
        distances, ...
        cutoff, ...
        nBootstrap, ...
        minimumFitR2, ...
        maxAttempts, ...
        eqsig, ...
        fitOptions, ...
        seedOffset, ...
        showProgress, ...
        conditionLabel)

    nDistances = numel(distances);

    bootMeanRT = ...
        nan(nDistances,nBootstrap);

    bootBorder = ...
        nan(1,nBootstrap);

    bootR2 = ...
        nan(1,nBootstrap);

    nAccepted = 0;
    nAttempts = 0;

    while nAccepted < nBootstrap && ...
            nAttempts < maxAttempts

        nAttempts = nAttempts + 1;

        % Deterministic but different resampling
        % on every bootstrap attempt
        rng(seedOffset+nAttempts,'twister');

        bootstrapMeans = ...
            nan(nDistances,1);

        for d = 1:nDistances

            currentData = ...
                conditionData{d};

            nTrials = ...
                size(currentData,1);

            if nTrials == 0
                break
            end

            sampledIndices = ...
                randi(nTrials,nTrials,1);

            sampledRT = ...
                currentData(sampledIndices,2);

            sampledRT = ...
                remove_wp3_outliers( ...
                    sampledRT,cutoff);

            if isempty(sampledRT)
                break
            end

            bootstrapMeans(d) = ...
                mean(sampledRT,'omitnan');
        end

        if ~all(isfinite(bootstrapMeans))
            continue
        end

        denominator = ...
            max(bootstrapMeans) - ...
            min(bootstrapMeans);

        if ~isfinite(denominator) || ...
                denominator <= eps
            continue
        end

        normalisedMeans = ...
            (bootstrapMeans-min(bootstrapMeans)) ./ ...
            denominator;

        try

            [fitObject,goodness] = fit( ...
                distances, ...
                normalisedMeans, ...
                eqsig, ...
                fitOptions);

            currentR2 = ...
                goodness.rsquare;

            currentBorder = ...
                fitObject.x0;

        catch
            continue
        end

        % Same accepted-fit rule used in WP3
        if ~isfinite(currentR2) || ...
                currentR2 < minimumFitR2 || ...
                ~isfinite(currentBorder)

            continue
        end

        nAccepted = nAccepted + 1;

        bootMeanRT(:,nAccepted) = ...
            bootstrapMeans;

        bootBorder(nAccepted) = ...
            currentBorder;

        bootR2(nAccepted) = ...
            currentR2;

        if showProgress == 1 && ...
                (mod(nAccepted,1000) == 0 || ...
                 nAccepted == nBootstrap)

            fprintf( ...
                '%s: %d/%d accepted fits (%d attempts).\n', ...
                conditionLabel, ...
                nAccepted, ...
                nBootstrap, ...
                nAttempts);
        end
    end

    if nAccepted < nBootstrap

        error(['Only %d of %d required %s bootstrap fits ' ...
            'were accepted after %d attempts. Inspect the ' ...
            'data or increase maxAttempts.'], ...
            nAccepted, ...
            nBootstrap, ...
            conditionLabel, ...
            nAttempts);
    end
end
