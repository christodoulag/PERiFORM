%% WP4 SPEEDPAD PRELIMINARY ANALYSIS
% Standalone analysis that reads the WP4 SpeedPad Excel dataset directly.
%
% Design:
%   - Within-participant Pull Training and Control conditions
%   - First assessment = assessment before the condition/interval
%   - Second assessment = assessment after the condition/interval
%   - Primary outcome = number of hits during the two-minute SpeedPad task
%
% Primary analysis:
%   Change_Intervention = Intervention_TEST2 - Intervention_TEST1
%   Change_Control      = Control_TEST2 - Control_TEST1
%   Interaction contrast = Change_Intervention - Change_Control
%
% The exact two-sided sign-flip test on the within-participant
% difference-in-change contrast is the primary inferential analysis.
% A paired-samples t-test on the two change scores is reported as a
% complementary parametric sensitivity analysis. Both tests are calculated
% locally and do not require Statistics and Machine Learning Toolbox.

clear; close all; clc;

dbstop if error
% dbstop if warning

%% ======================== USER SETTINGS ==============================

% Full path to the Excel workbook. This is the only path that normally
% needs to be changed. Analysis outputs are saved beside the workbook.
dataFile = '';

% Worksheet containing the SpeedPad data.
sheetName = 'Sheet1';

outputFolder = fileparts(dataFile);

if isempty(outputFolder)
    outputFolder = pwd;
end

% All SpeedPad trials currently lasted two minutes.
taskDurationMinutes = 2;

% Set to true to create and export the figures.
makeFigures = true;

% Set to true to attempt the equivalent 2 x 2 repeated-measures ANOVA.
% The primary change-score analysis below is performed in all cases.
runRepeatedMeasuresANOVA = true;

%% ======================== IMPORT EXCEL DATA ==========================

if ~isfile(dataFile)
    error(['The SpeedPad Excel file was not found:\n%s\n' ...
        'Update dataFile in USER SETTINGS.'],dataFile);
end

rawData = readcell(dataFile,'Sheet',sheetName);

% Expected source layout:
%   A  = participant SN
%   B  = Intervention TEST1 label
%   C  = Intervention TEST1 Hits
%   D  = Intervention TEST1 Misses
%   E  = Intervention TEST2 label
%   F  = Intervention TEST2 Hits
%   G  = Intervention TEST2 Misses
%   H  = blank separator
%   I  = Control TEST1 label
%   J  = Control TEST1 Hits
%   K  = Control TEST1 Misses
%   L  = Control TEST2 label
%   M  = Control TEST2 Hits
%   N  = Control TEST2 Misses

if size(rawData,1) < 2 || size(rawData,2) < 14
    error(['The workbook does not match the expected SpeedPad layout. ' ...
        'Expected data in columns A:N.']);
end

if ~strcmpi(strtrim(string(rawData{1,1})),'SN')
    error('Cell A1 must contain the participant header SN.');
end

% Detect participant rows from numeric values in column A. Blank formatted
% rows beneath the dataset are ignored automatically.
participantCandidates = extract_speedpad_counts( ...
    rawData(2:end,1),false,'SN');
participantRowMask = isfinite(participantCandidates);

if ~any(participantRowMask)
    error('No participant rows were detected in column A.');
end

participantID = participantCandidates(participantRowMask);
participantRows = rawData(1+find(participantRowMask),:);

% Confirm that condition labels have not shifted to different columns.
interventionLabels1 = strtrim(string(participantRows(:,2)));
interventionLabels2 = strtrim(string(participantRows(:,5)));
controlLabels1 = strtrim(string(participantRows(:,9)));
controlLabels2 = strtrim(string(participantRows(:,12)));

if ~all(strcmpi(interventionLabels1,'Intervention')) || ...
        ~all(strcmpi(interventionLabels2,'Intervention'))
    error(['Intervention labels were not found in the expected ' ...
        'TEST1/TEST2 columns B and E.']);
end

if ~all(strcmpi(controlLabels1,'Control')) || ...
        ~all(strcmpi(controlLabels2,'Control'))
    error(['Control labels were not found in the expected ' ...
        'TEST1/TEST2 columns I and L.']);
end

% Values such as "122 (0.0%%)" are stored as text in Excel. The helper
% function extracts the first numeric value from every populated cell.
interventionTest1 = extract_speedpad_counts( ...
    participantRows(:,3),true,'Intervention TEST1 Hits');
interventionMissesTest1 = extract_speedpad_counts( ...
    participantRows(:,4),true,'Intervention TEST1 Misses');

interventionTest2 = extract_speedpad_counts( ...
    participantRows(:,6),true,'Intervention TEST2 Hits');
interventionMissesTest2 = extract_speedpad_counts( ...
    participantRows(:,7),true,'Intervention TEST2 Misses');

controlTest1 = extract_speedpad_counts( ...
    participantRows(:,10),true,'Control TEST1 Hits');
controlMissesTest1 = extract_speedpad_counts( ...
    participantRows(:,11),true,'Control TEST1 Misses');

controlTest2 = extract_speedpad_counts( ...
    participantRows(:,13),true,'Control TEST2 Hits');
controlMissesTest2 = extract_speedpad_counts( ...
    participantRows(:,14),true,'Control TEST2 Misses');

%% ======================== VALIDATION =================================

dataColumns = { ...
    interventionTest1,interventionTest2,controlTest1,controlTest2, ...
    interventionMissesTest1,interventionMissesTest2, ...
    controlMissesTest1,controlMissesTest2};

nParticipants = numel(participantID);

if nParticipants < 2
    error('At least two participants are required.');
end

for columnNumber = 1:numel(dataColumns)
    currentColumn = dataColumns{columnNumber};

    if numel(currentColumn) ~= nParticipants
        error('All data columns must contain one value per participant.');
    end

    if any(~isfinite(currentColumn))
        error('Missing or non-finite values were detected.');
    end

    if any(currentColumn < 0) || ...
            any(abs(currentColumn-round(currentColumn)) > eps)
        error('SpeedPad Hits and Misses must be non-negative integers.');
    end
end

if numel(unique(participantID)) ~= nParticipants
    error('Participant identifiers must be unique.');
end

if taskDurationMinutes <= 0
    error('taskDurationMinutes must be greater than zero.');
end

if ~isfolder(outputFolder)
    mkdir(outputFolder);
end

%% ======================== DERIVED VARIABLES ==========================

changeIntervention = interventionTest2-interventionTest1;
changeControl = controlTest2-controlTest1;

% Primary Time-by-Condition interaction contrast.
differenceInChange = changeIntervention-changeControl;

interventionTest1PerMinute = interventionTest1/taskDurationMinutes;
