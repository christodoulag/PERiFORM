%% ======================== LOCAL FUNCTION =============================

function [pValue,observedStatistic,nPermutations,method] = ...
    sign_flip_test_base(differences)

    % Two-sided paired sign-flip permutation test implemented using only
    % base MATLAB. The statistic is the mean within-participant contrast.
    % For up to 20 participants, every possible sign allocation is tested.
    % For larger samples, a reproducible Monte Carlo approximation is used
    % to avoid excessive memory use and computation time.
    differences = differences(:);

    if any(~isfinite(differences))
        error(['The sign-flip test received missing or ' ...
            'non-finite values.']);
    end

    sampleSize = numel(differences);

    if sampleSize < 1
        error('At least one paired contrast is required.');
    end

    observedStatistic = mean(differences);
    comparisonTolerance = ...
        1e-12*max(1,abs(observedStatistic));
    maximumExactSampleSize = 20;

    if sampleSize <= maximumExactSampleSize
        nPermutations = 2^sampleSize;
        method = "Exact enumeration";
        extremeCount = 0;
        chunkSize = 100000;

        for firstPermutation = 0:chunkSize:(nPermutations-1)
            lastPermutation = min( ...
                firstPermutation+chunkSize-1,nPermutations-1);
            permutationIDs = uint64( ...
                (firstPermutation:lastPermutation)');
            permutedSums = zeros(numel(permutationIDs),1);

            for participantNumber = 1:sampleSize
                currentSigns = 2*double(bitget( ...
                    permutationIDs,participantNumber))-1;
                permutedSums = permutedSums + ...
                    currentSigns*differences(participantNumber);
            end

            permutedStatistics = permutedSums/sampleSize;
            extremeCount = extremeCount + sum( ...
                abs(permutedStatistics) >= ...
                abs(observedStatistic)-comparisonTolerance);
        end

        pValue = extremeCount/nPermutations;
    else
        % Reproducible approximation for future larger samples.
        nPermutations = 100000;
        method = "Monte Carlo approximation";
        rng(20260804,'twister');
        extremeCount = 0;
        chunkSize = 10000;
        permutationsCompleted = 0;

        while permutationsCompleted < nPermutations
            currentChunk = min( ...
                chunkSize,nPermutations-permutationsCompleted);
            randomSigns = 2*(rand(currentChunk,sampleSize) >= 0.5)-1;
            permutedStatistics = mean( ...
                randomSigns.*differences',2);
            extremeCount = extremeCount + sum( ...
                abs(permutedStatistics) >= ...
                abs(observedStatistic)-comparisonTolerance);
            permutationsCompleted = ...
                permutationsCompleted+currentChunk;
        end

        % Plus-one correction for a Monte Carlo randomisation p-value.
        pValue = (extremeCount+1)/(nPermutations+1);
    end

    pValue = min(max(pValue,0),1);
end

function [rejectNull,pValue,confidenceInterval,stats] = ...
    paired_ttest_base(firstMeasure,secondMeasure,alpha)

    % Two-sided paired-samples t-test implemented with base MATLAB.
    % The test is applied to firstMeasure-secondMeasure.
    differences = firstMeasure(:)-secondMeasure(:);

    if any(~isfinite(differences))
        error('The paired t-test received missing or non-finite values.');
    end

    sampleSize = numel(differences);

    if sampleSize < 2
        error('At least two paired observations are required.');
    end

    degreesOfFreedom = sampleSize-1;
    meanDifference = mean(differences);
    standardDeviation = std(differences);
    standardError = standardDeviation/sqrt(sampleSize);

    if standardError > 0
        tStatistic = meanDifference/standardError;
        pValue = student_t_two_sided_p_base( ...
            tStatistic,degreesOfFreedom);

        criticalT = student_t_inverse_base( ...
            1-alpha/2,degreesOfFreedom);

        confidenceInterval = meanDifference + ...
            [-1 1]*criticalT*standardError;
    else
        if meanDifference == 0
            tStatistic = 0;
            pValue = 1;
        else
            tStatistic = sign(meanDifference)*Inf;
            pValue = 0;
        end

        confidenceInterval = [meanDifference meanDifference];
    end

    pValue = min(max(pValue,0),1);
    rejectNull = pValue < alpha;

    stats = struct( ...
        'tstat',tStatistic, ...
        'df',degreesOfFreedom, ...
        'sd',standardDeviation);
end

function pValue = student_t_two_sided_p_base( ...
    tStatistic,degreesOfFreedom)

    % For a Student-t variable, the two-sided tail probability can be
    % calculated directly from the regularised incomplete beta function.
    if isinf(tStatistic)
        pValue = 0;
        return
    end

    betaArgument = degreesOfFreedom ./ ...
        (degreesOfFreedom+tStatistic.^2);

    pValue = betainc( ...
        betaArgument,degreesOfFreedom/2,0.5);
end

function tQuantile = student_t_inverse_base( ...
    probability,degreesOfFreedom)

    % Inverse Student-t CDF calculated from BETAINCINV. This replaces TINV,
    % which belongs to Statistics and Machine Learning Toolbox.
    if probability <= 0 || probability >= 1
        error('Student-t probability must be between zero and one.');
    end

    if probability == 0.5
        tQuantile = 0;
        return
    end

    if probability < 0.5
        tQuantile = -student_t_inverse_base( ...
            1-probability,degreesOfFreedom);
        return
    end

    twoSidedTail = 2*(1-probability);
    betaQuantile = betaincinv( ...
        twoSidedTail,degreesOfFreedom/2,0.5);

    tQuantile = sqrt( ...
        degreesOfFreedom*(1-betaQuantile)/betaQuantile);
end

function numericValues = extract_speedpad_counts( ...
    rawColumn,requireComplete,variableLabel)

    % Extract the first numeric value from cells formatted as, for example,
    % "122 (0.0%)". Numeric Excel cells are also accepted directly.
    numericValues = nan(numel(rawColumn),1);

    for rowNumber = 1:numel(rawColumn)
        currentValue = rawColumn{rowNumber};

        if isnumeric(currentValue) && isscalar(currentValue)
            if isfinite(currentValue)
                numericValues(rowNumber) = double(currentValue);
            end
            continue
        end

        currentText = strtrim(string(currentValue));

        if ismissing(currentText) || strlength(currentText) == 0
            continue
        end

        firstNumber = regexp( ...
            char(currentText), ...
            '[-+]?(?:\d+\.?\d*|\.\d+)', ...
            'match','once');

        if ~isempty(firstNumber)
            numericValues(rowNumber) = str2double(firstNumber);
        end
    end

    if requireComplete && any(~isfinite(numericValues))
        badRows = find(~isfinite(numericValues));
        error(['Could not extract a numeric value for %s in ' ...
            'participant-data row(s): %s.'], ...
            variableLabel,mat2str(badRows'));
    end
end

